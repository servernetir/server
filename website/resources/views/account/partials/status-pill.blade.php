{{--
  قرصِ وضعیتِ سرویس — یک نگاشت، برای هر چهار اتاق.

  🔴 چرا این‌جا و نه `Service::statusBadge()`: آن متد **فارسیِ سخت‌کد** و یک
  رنگِ خامِ hex برمی‌گرداند. تا امروز صفحهٔ سرویس‌ها همان را چاپ می‌کرد، پس
  مشتریِ /en و /tr یک صفحهٔ ترجمه‌شده می‌دید که وسطش قرصِ فارسی بود — و رنگش
  هم `background:{{ $hex }}22` بود، یعنی سایه‌ای ۱۳٪ از رنگِ خودِ متن که در
  تمِ روشن کنتراست نمی‌آورد. `statusBadge()` دست‌نخورده می‌مانَد (پنلِ مدیریتِ
  تک‌زبانه از آن می‌خوانَد و تستی هم دارد)، ولی پنلِ مشتری از این‌جا می‌گیرد.

  ورودی: $s (Service)
--}}
@php
  /*
   | نگاشتِ **کد** ⇒ [کلاسِ قرص، کلیدِ ui]. کد است که در دیتابیس می‌نشیند و
   | هرگز عوض نمی‌شود؛ متن فقط نمایش است.
   */
  $pill = match ($s->status) {
      'active'             => ['ok', 'ui.svc_on'],
      'suspended'          => ['danger', 'ui.svc_suspended'],
      'awaiting_provision' => ['info', 'ui.cs_status_preparing'],
      'provision_failed'   => ['danger', 'ui.st_failed'],
      'expired'            => ['mute', 'ui.st_expired'],
      default              => ['mute', 'ui.st_unknown'],
  };

  /*
   | ⚠️ سرویسی که «فعال» است ولی تحویلش شکسته، برای مشتری فعال **نیست**.
   | ردیفِ قبلی همان قرصِ سبزِ سرویسِ سالم را می‌گرفت و مشتری فکر می‌کرد
   | همه‌چیز مرتب است در حالی که هیچ سروری نداشت.
   */
  if ($s->status === 'active' && $s->provision_status === 'failed') {
      $pill = ['danger', 'ui.st_failed'];
  }
@endphp
<span class="pnl-pill {{ $pill[0] }}">{{ __($pill[1]) }}</span>
