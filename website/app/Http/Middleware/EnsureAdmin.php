<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Symfony\Component\HttpFoundation\Response;

/**
 * فقط **مدیر** — نه هر کاربرِ واردشده به پنلِ مدیریت.
 *
 * ⚠️ چرا لازم شد: گروهِ `/admin` تنها پشتِ `auth:web` بود و هیچ‌جا نقش سنجیده
 * نمی‌شد، در حالی که پنل اجازه می‌دهد کاربر با نقشِ `author` (برای نوشتنِ بلاگ)
 * ساخته شود و ورودش هم نقش را نمی‌سنجد. نتیجه: یک نویسنده می‌توانست
 * `/admin/cloud/probe` را ببیند (ساختارِ خامِ پاسخِ زیرساخت و اطلاعاتِ حسابِ ما)
 * و `/admin/cloud/sync` را بزند که سهمیهٔ API را می‌سوزاند، یا به تنظیمات و
 * قیمت‌ها دست ببرد.
 *
 * چرا روی **همهٔ** /admin نگذاشتیم: مدیریتِ محتوا (بلاگ، پایگاه دانش، نظرات)
 * عمداً برای نقشِ نویسنده باز است — بستنش کارِ واقعیِ او را می‌بندد. پس این
 * میان‌افزار فقط روی مسیرهای **پرهزینه یا حساس** می‌نشیند: زیرساختِ ابری،
 * تنظیمات، سرورها، پکیج‌ها، مالی و ورود به‌جای مشتری.
 *
 * ۴۰۳ و نه ۴۰۴: این‌جا مخاطب یک **همکارِ واردشده** است که سایدبارِ پنل را
 * می‌بیند و می‌داند این بخش‌ها وجود دارند. «پیدا نشد» گفتن به او نه چیزی پنهان
 * می‌کند نه کمکی است — فقط او را سرگردان و پشتیبانی را سخت می‌کند («لینک خراب
 * است!»). ۴۰۴ برای پنهان‌کردن از غریبه معنا دارد، و غریبه پیش‌تر با `auth:web`
 * رد شده است.
 *
 * چون این میان‌افزار **بعد از** `auth:web` می‌نشیند، وقتی اجرا می‌شود کاربر
 * قطعاً واردشده است؛ ولی بررسیِ null نگه داشته می‌شود تا اگر روزی ترتیب عوض شد،
 * به‌جای خطای مرگبار، دسترسی بسته شود.
 */
class EnsureAdmin
{
    public function handle(Request $request, Closure $next): Response
    {
        $user = Auth::guard('web')->user();

        abort_unless($user !== null && $user->isAdmin(), 403,
            'این بخش فقط برای مدیر است.');

        return $next($request);
    }
}
