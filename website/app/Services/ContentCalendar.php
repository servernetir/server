<?php

namespace App\Services;

use App\Models\Post;
use App\Support\Jalali;
use Illuminate\Support\Carbon;

/**
 * تقویمِ انتشار محتوا — تصمیم می‌گیرد هر مقاله «کِی» منتشر شود.
 *
 * ═══ چرا این کلاس لازم شد ═══
 *
 * تا پیش از این، `content:generate` زمانِ انتشار را با `random_int` در بازهٔ
 * «N روزِ آینده» می‌ریخت. نتیجه در عمل دو حالتِ بد داشت:
 *
 *   ۱) چند مقاله روی یک روز می‌افتاد و روزهای دیگر خالی می‌ماند —
 *      یعنی سایت به‌جای جریانِ ثابت، پالسی منتشر می‌کرد. گوگل جریانِ ثابت را
 *      نشانهٔ سایتِ زنده می‌داند؛ پالسِ نامنظم را نه.
 *   ۲) `--daily` دقیقاً یک مقاله در روز می‌گذاشت و **بر اساسِ type** می‌شمرد،
 *      پس بلاگ و پایگاه دانش هرکدام جداگانه روزی یکی می‌گذاشتند و
 *      هیچ‌کس نمی‌دانست مجموعِ روز چند تا شد.
 *
 * این کلاس یک سهمیهٔ **روزانه و مشترک بین همهٔ نوع‌ها** می‌سازد: هر روز
 * ۲ تا ۵ مطلب، با آهنگی که به روزِ هفتهٔ ایرانی می‌خورد.
 *
 * ═══ چرا سهمیه ثابت نیست ═══
 *
 * انتشارِ دقیقاً ۴ مطلب در روز، هر روز، ساعتِ گِرد، الگویی می‌سازد که از
 * بیرون کاملاً ماشینی به‌نظر می‌رسد. سهمیه بر اساسِ **خودِ تاریخ** به‌شکلِ
 * قطعی (نه تصادفی) بین ۲ تا ۵ نوسان می‌کند: قطعی است تا دو بار اجرا کردنِ
 * فرمان همان جواب را بدهد، و متغیر است تا الگو نداشته باشد.
 *
 * پنج‌شنبه و جمعه سبک‌تر است چون ترافیکِ B2B ایران در آخرِ هفته می‌افتد و
 * مقالهٔ خوب را نباید در کم‌بازدیدترین روز سوزاند.
 */
class ContentCalendar
{
    /** آخرین روزِ سالِ ۱۴۰۵ — افقِ برنامه‌ریزی */
    public const PLAN_UNTIL_JYEAR = 1405;

    /**
     * پرونده‌های برنامهٔ محتوا، به همان ترتیبی که `content:generate` می‌خواند.
     *
     * ⚠️ اگر برنامهٔ تازه‌ای اضافه شد و این‌جا نیامد، تقویم صف را کوچک‌تر از
     * واقع می‌بیند و سهمیه را کم می‌گذارد — یعنی ته صف بی‌صدا به سالِ بعد
     * می‌افتد. `ContentPipelineTest` همین را می‌گیرد.
     */
    public const PLANS = ['docs-plan', 'blog-1405', 'kb-1405', 'docs-1405'];

    /**
     * باندِ سهمیهٔ روزانه — یک تصمیمِ طراحی، نه عددی دلخواه.
     *
     * 🔴 کمتر از ۲ ⇒ فید تُنُک می‌شود و «سایتِ زنده» بودن را از دست می‌دهد.
     * 🔴 بیشتر از ۵ ⇒ سایت به فیدِ هرزنامه‌ای شبیه می‌شود و کیفیتِ درک‌شده
     *    پایین می‌آید — چیزی که هیچ‌کس در هیچ گزارشی نمی‌بیند.
     *
     * ⚠️ `planQuota()` هرگز از این باند بیرون نمی‌زند، حتی اگر صف جا نشود.
     * آن یک تصمیمِ انسانی است و `ContentPipelineTest` نشانش می‌دهد.
     */
    public const QUOTA_MIN = 2;

    public const QUOTA_MAX = 5;

    /** ساعاتِ مجازِ انتشار: صبحِ کاری تا شبِ زودهنگام */
    private const HOUR_MIN = 9;

    private const HOUR_MAX = 21;

    /** @var array<string,int> کشِ شمارشِ روزها در یک اجرا */
    private array $taken = [];

    /** @var array<string,list<int>> دقیقه‌های اشغال‌شدهٔ هر روز (به‌صورتِ دقیقه از نیمه‌شب) */
    private array $minutes = [];

    private ?Carbon $cursor = null;

    /**
     * سهمیهٔ **نهایی** هر روز، پس از تنظیم با اندازهٔ صف.
     *
     * 🔴 چرا وجود دارد: سهمیه قبلاً با دست کالیبره شده بود و داکبلاکش می‌گفت
     * «اگر موضوع‌ها را کم یا زیاد کردی این‌جا را هم تنظیم کن». ولی چیزی که
     * کالیبراسیون را می‌شکست تغییرِ موضوع‌ها نبود — **گذرِ زمان** بود: پایانِ
     * برنامه ثابت است، پس هر روز پنجره یک روز کوتاه‌تر و ظرفیت ~۳٫۵ کمتر
     * می‌شود، در حالی که صف فقط به‌اندازهٔ تولیدِ واقعی آب می‌رود.
     *
     * ⚠️ عددی که هر چند هفته دستی تنظیم شود، تستی می‌سازد که یا نادیده گرفته
     * می‌شود یا خاموش. پس سهمیه از **خودِ صف** مشتق می‌شود.
     *
     * @var array<string,int>
     */
    private array $quota = [];

    public function __construct()
    {
        $this->load();
        $this->calibrate();
    }

    /**
     * سهمیهٔ انتشارِ یک روز: عددی بین ۲ تا ۵، قطعی نسبت به تاریخ.
     *
     * ⚠️ عمداً از `random_int` استفاده نمی‌شود. اگر سهمیه تصادفی باشد، اجرای
     * دومِ همان فرمان می‌تواند سهمیهٔ دیروز را کمتر ببیند و مقاله‌ای را روی
     * روزی بگذارد که قبلاً پر شده بود.
     */
    public function quotaFor(Carbon $day): int
    {
        /*
        | 🔴 نقشهٔ تنظیم‌شده اگر باشد، **همان** حرفِ آخر است.
        |
        | نسخهٔ قبل شکلِ پایه را می‌ساخت و بعد افزایه را جای دیگری کلامپ می‌کرد.
        | نتیجه: باندِ ۲–۵ دو مالک داشت. جهش‌سنجی نشان داد حذفِ سقف از هیچ
        | تستی رد نمی‌شود، چون تست‌ها خودشان کلامپ را دوباره اعمال می‌کردند —
        | یعنی فیکسچر از فهمِ من ساخته شده بود نه از کد.
        */
        return $this->quota[$day->toDateString()] ?? self::baseQuotaFor($day);
    }

    /**
     * شکلِ پایهٔ یک روز، پیش از هر تنظیمی: عددی بین ۲ تا ۵، قطعی نسبت به تاریخ.
     *
     * ⚠️ عمداً `random_int` نیست. اگر تصادفی باشد، اجرای دومِ همان فرمان
     * می‌تواند سهمیهٔ دیروز را کمتر ببیند و مقاله‌ای را روی روزِ پرشده بگذارد.
     */
    public static function baseQuotaFor(Carbon $day): int
    {
        // پنج‌شنبه و جمعه سبک: ترافیکِ B2B ایران در آخرِ هفته می‌افتد و
        // مقالهٔ خوب را نباید در کم‌بازدیدترین روز سوزاند.
        if (Jalali::weekdayIndex($day) >= 5) {
            return 2;
        }

        /*
         * شنبه تا چهارشنبه: معمولاً ۳، گاهی ۴، به‌ندرت ۵ — تا الگو نداشته باشد.
         *
         * ⚠️ این فقط **بافتِ** توزیع است، نه جمعِ ظرفیت. جمع را `planQuota()`
         * از اندازهٔ صف مشتق می‌کند، پس عددهای این‌جا تعیین می‌کنند کدام روز
         * شلوغ‌تر باشد، نه اینکه در کل چند مطلب جا شود.
         *
         * ═══ 🔴 چرا دیگر «تنظیمِ دستی» لازم نیست ═══
         *
         * ۸ شهریور ۱۴۰۵ همکار این توزیع را یک پله بالا برد و دلیلش را نوشت:
         * تنظیمِ قبلی ظرفیتی می‌داد که فقط ۱ نوبت از صف بیشتر بود، و چون
         * پنجرهٔ سال هر روز کوتاه‌تر می‌شود (~۳٫۵ نوبت در روز) ولی صف فقط با
         * تولید کم می‌شود، دو روز بعد ظرفیت از صف کمتر شد و تست قرمز شد.
         *
         * تشخیصش دقیقاً درست بود — و همان تشخیص می‌گوید که پلهٔ بعدی هم چند
         * هفته بعد کم می‌آورد. هر بار که این عدد را با دست بالا ببریم، فقط
         * تاریخِ قرمزیِ بعدی را عقب انداخته‌ایم.
         *
         * پس نتیجهٔ همان تحلیل این‌جا ساختاری شد: ظرفیت از خودِ صف می‌آید.
         * پلهٔ همکار حفظ شده چون بافتِ توزیع را تعیین می‌کند، ولی دیگر چیزی
         * به آن وابسته نیست و کسی لازم نیست دوباره کالیبره‌اش کند.
         */        return match (crc32($day->toDateString()) % 8) {
            3, 4       => 4,
            5, 6, 7    => 5,
            default    => 3,
        };
    }
    /**
     * زمانِ انتشارِ بعدی. روزها را از فردا جلو می‌رود تا روزی پیدا کند که
     * سهمیه‌اش پر نشده باشد، سپس ساعتی می‌دهد که با بقیهٔ همان روز فاصله دارد.
     *
     * اگر تقویمِ سال پر شده باشد `null` برمی‌گرداند — فراخوان باید این را
     * جدی بگیرد و تولید را متوقف کند، نه اینکه مقاله را روی سالِ بعد بریزد.
     */
    public function nextSlot(?string $preferredDate = null): ?Carbon
    {
        $day = $this->startDay($preferredDate);
        $end = $this->endOfPlan();
        $pinned = $preferredDate !== null;

        while ($day->lte($end)) {
            $key = $day->toDateString();
            if (($this->taken[$key] ?? 0) < $this->quotaFor($day)) {
                // مطلبِ تاریخ‌دار نباید مکان‌نمای عمومی را جلو ببرد، وگرنه یک
                // مقالهٔ نوروزی کلِ صف را به اسفند پرت می‌کند و پنج ماه سکوت
                // می‌سازد
                if (! $pinned) {
                    $this->cursor = $day->copy();
                }

                return $this->reserve($day);
            }
            $day = $day->copy()->addDay();
        }

        return null;
    }

    /**
     * نقطهٔ شروعِ جستجو. تاریخِ درخواستی فقط وقتی پذیرفته می‌شود که در آینده و
     * داخلِ سالِ برنامه باشد؛ تاریخِ گذشته یعنی مطلبی که هرگز در فید دیده
     * نمی‌شود، پس به صفِ عادی برمی‌گردد.
     */
    private function startDay(?string $preferredDate): Carbon
    {
        $default = $this->cursor ?? now()->addDay()->startOfDay();

        if ($preferredDate === null || trim($preferredDate) === '') {
            return $default;
        }

        try {
            $wanted = Carbon::parse($preferredDate)->startOfDay();
        } catch (\Throwable $e) {
            return $default;
        }

        $floor = now()->addDay()->startOfDay();

        return ($wanted->lt($floor) || $wanted->gt($this->endOfPlan())) ? $default : $wanted;
    }

    /**
     * سهمیهٔ روزانه را با اندازهٔ **واقعیِ** صف و پنجرهٔ باقی‌مانده تنظیم کن.
     *
     * ═══ 🔴 خرابی‌ای که این می‌بندد ═══
     *
     * ظرفیت با دست کالیبره شده بود و داکبلاکش می‌گفت «اگر موضوع‌ها را کم یا
     * زیاد کردی این‌جا را هم تنظیم کن». ولی چیزی که کالیبراسیون را می‌شکست،
     * تغییرِ موضوع‌ها نبود — **گذرِ زمان** بود:
     *
     *   پایانِ برنامه ثابت است (۲۹ اسفند ۱۴۰۵)، پس هر روز پنجره یک روز
     *   کوتاه‌تر و ظرفیت حدودِ ۳٫۵ کمتر می‌شود، در حالی که صف فقط به‌اندازهٔ
     *   تولیدِ واقعی آب می‌رود. یعنی کالیبراسیون به‌تدریج و بی‌صدا فاسد می‌شد.
     *
     * ⚠️ و هر دو جهتِ خرابی این‌جا بسته می‌شود، نه فقط کمبود:
     *
     *   کم  ⇒ ته صف به سالِ بعد می‌افتد.
     *   زیاد ⇒ `nextSlot()` حریص است، روزهای اول را پر می‌کند، صف زودتر تمام
     *          می‌شود و **هفته‌های آخرِ سال خالی می‌مانَد** — بی‌هیچ خطایی.
     *
     * پس افزایه می‌تواند منفی هم باشد.
     */
    private function calibrate(): void
    {
        $pending = $this->pendingCount();

        if ($pending === null) {
            return;   // برنامه‌ای در دسترس نیست ⇒ همان شکلِ پایه
        }

        $days = 0;
        $base = 0;
        $day = now()->addDay()->startOfDay();
        $end = $this->endOfPlan();

        // ⚠️ عمداً `quotaFor()` صدا زده می‌شود در حالی که `lift` هنوز صفر است:
        //    اگر بعد از تنظیم می‌سنجید، پایه به خودش ارجاع می‌داد.
        while ($day->lte($end)) {
            $base += max(0, $this->quotaFor($day) - ($this->taken[$day->toDateString()] ?? 0));
            $days++;
            $day = $day->addDay();
        }

        if ($days === 0) {
            return;
        }

        $shape = [];
        $day = now()->addDay()->startOfDay();
        $end = $this->endOfPlan();

        while ($day->lte($end)) {
            $shape[$day->toDateString()] = self::baseQuotaFor($day);
            $day = $day->addDay();
        }

        $this->quota = self::planQuota($pending - $base, $shape);
    }

    /**
     * حسابِ محضِ سهمیه: «چقدر کم/زیاد داریم» → «هر روز چند تا».
     *
     * 🔴 عمداً `static` و بی‌وابستگی به دیتابیس، پرونده و `now()`.
     *
     * ⚠️ دلیلش یک شکستِ واقعیِ جهش‌سنجی است: دو شاخهٔ این حساب — بخشِ صحیح و
     * سقفِ باند — با دادهٔ **امروز** اصلاً اجرا نمی‌شوند (کمبودِ ۴۳ در ۲۰۲ روز
     * یعنی زیر یکی در روز). پس حذفشان از چشمِ کلِ سوئیت می‌گریخت. تا وقتی
     * حساب داخلِ متدی بود که صف را از پرونده و پُست‌ها می‌خواند، هیچ تستی
     * نمی‌توانست کمبودِ بزرگ بسازد. جدا که شد، هر سناریویی سنجیدنی است.
     *
     * 🔴 و خروجی **سهمیهٔ نهایی** است، نه یک افزایه که جای دیگری کلامپ شود.
     * نسخهٔ قبل افزایه برمی‌گرداند و باند دو مالک داشت؛ تست‌ها هم کلامپ را
     * خودشان دوباره اعمال می‌کردند، پس حذفِ سقف از همه‌شان سالم رد می‌شد —
     * فیکسچری که از فهمِ نویسنده ساخته شده بود، نه از کد.
     *
     * @param  int  $extra  اختلافِ صف و ظرفیتِ پایه (منفی = ظرفیتِ اضافی)
     * @param  array<string,int>  $shape  سهمیهٔ پایهٔ هر روز
     * @return array<string,int>  سهمیهٔ نهایی هر روز، همیشه در باندِ ۲ تا ۵
     */
    public static function planQuota(int $extra, array $shape): array
    {
        $days = count($shape);

        if ($days === 0) {
            return [];
        }

        /*
        | بخشِ صحیح روی همهٔ روزها، باقیمانده روی تعدادی روزِ مشخص.
        |
        | 🔴 گِردکردنِ ساده کافی نیست: نسخهٔ اول `round($extra / $days)` بود و
        | روی دادهٔ واقعی صفر داد — کمبودِ ۴۳ تقسیم بر ۲۰۲ روز می‌شود ۰٫۲۱ —
        | یعنی هر ۴۳ مطلب سرِ جایشان به سالِ بعد می‌افتادند. تنظیمی که فقط
        | برای کمبودهای بزرگ کار می‌کرد و برای حالتِ معمول بی‌صدا هیچ نمی‌کرد.
        */
        $lift = intdiv($extra, $days);
        $rem = $extra - ($lift * $days);

        /*
        | 🔴 باندِ ۲ تا ۵ یک تصمیمِ طراحی است، نه عددی دلخواه:
        |
        |   کمتر از ۲ ⇒ فید تُنُک می‌شود و «سایتِ زنده» بودن را از دست می‌دهد.
        |   بیشتر از ۵ ⇒ سایت به فیدِ هرزنامه‌ای شبیه می‌شود و کیفیتِ درک‌شده
        |                 پایین می‌آید — چیزی که هیچ‌کس در گزارش نمی‌بیند.
        |
        | ⚠️ پس اگر صف حتی با سهمیهٔ ۵ جا نشود، تقویم **خودش را درست نمی‌کند**.
        | آن یک تصمیمِ انسانی است (موضوع کم کن یا افق را جلو ببر)، و
        | `ContentPipelineTest` همان‌جا قرمز می‌شود تا کسی ببیندش.
        */
        $out = [];

        foreach ($shape as $key => $base) {
            $out[$key] = max(self::QUOTA_MIN, min(self::QUOTA_MAX, $base + $lift));
        }

        if ($rem === 0) {
            return $out;
        }

        /*
        | کدام روزها باقیمانده را بگیرند؟ قطعی، نه تصادفی — وگرنه دو بار اجرا
        | کردنِ همان فرمان دو تقویمِ متفاوت می‌سازد و مقاله‌ای روی روزِ پرشده
        | می‌نشیند.
        |
        | ⚠️ ترتیب بر اساسِ هشِ تاریخ است نه خودِ تاریخ: با ترتیبِ تقویمی همهٔ
        | روزهای اضافه به ابتدای دوره می‌چسبیدند و همان «پالسِ اول، سکوتِ بعد»ی
        | را می‌ساختند که این کلاس اصلاً برای رفعش نوشته شد.
        |
        | 🔴 و فقط روزهایی که واقعاً **جا دارند**. نسخهٔ اول باقیمانده را روی
        | چند روزِ اولِ فهرست می‌گذاشت بی‌آنکه ببیند آن روز از قبل روی سقف
        | نشسته یا نه — چهار واحد در کلامپ بلعیده می‌شد و ظرفیت باز هم از صف
        | کمتر می‌ماند. تنظیمی که گزارش می‌داد کار کرده ولی نکرده بود.
        */
        $order = [];

        foreach (array_keys($shape) as $key) {
            $order[$key] = crc32($key);
        }

        asort($order);

        $sign = $rem > 0 ? 1 : -1;
        $left = abs($rem);

        foreach (array_keys($order) as $key) {
            if ($left === 0) {
                break;
            }

            $next = $out[$key] + $sign;

            if ($next >= self::QUOTA_MIN && $next <= self::QUOTA_MAX) {
                $out[$key] = $next;
                $left--;
            }
        }

        return $out;
    }
    /**
     * چند مطلبِ برنامه‌ریزی‌شده هنوز ساخته نشده؟ (`null` اگر نشد فهمید)
     *
     * همان دیدی که `content:generate` دارد: ردیفی که اسلاگش در `posts` نیست.
     *
     * ⚠️ خطا **بلعیده** می‌شود و `null` برمی‌گردد: تقویم نباید به‌خاطرِ یک
     * پروندهٔ برنامهٔ غایب از کار بیفتد. در آن حالت همان شکلِ پایه می‌مانَد،
     * که رفتارِ قبلی است.
     */
    private function pendingCount(): ?int
    {
        try {
            $slugs = [];

            foreach (self::PLANS as $plan) {
                $path = resource_path('content/'.$plan.'.php');

                if (! is_file($path)) {
                    continue;
                }

                foreach ((array) require $path as $row) {
                    if (isset($row['slug'])) {
                        $slugs[(string) $row['slug']] = true;
                    }
                }
            }

            if ($slugs === []) {
                return null;
            }

            $built = Post::query()->whereIn('slug', array_keys($slugs))->pluck('slug');

            return count($slugs) - $built->count();
        } catch (\Throwable) {
            return null;
        }
    }

    /** ظرفیتِ باقی‌ماندهٔ تقویم تا پایانِ سال — برای گزارش و برنامه‌ریزی */
    public function remainingCapacity(): int
    {
        $free = 0;
        $day = now()->addDay()->startOfDay();
        $end = $this->endOfPlan();

        while ($day->lte($end)) {
            $free += max(0, $this->quotaFor($day) - ($this->taken[$day->toDateString()] ?? 0));
            $day = $day->addDay();
        }

        return $free;
    }

    /** آخرین لحظهٔ قابلِ برنامه‌ریزی: پایانِ ۲۹ اسفند ۱۴۰۵ */
    public function endOfPlan(): Carbon
    {
        $last = Jalali::daysInMonth(self::PLAN_UNTIL_JYEAR, 12);
        [$gy, $gm, $gd] = Jalali::toGregorian(self::PLAN_UNTIL_JYEAR, 12, $last);

        return Carbon::create($gy, $gm, $gd)->endOfDay();
    }

    /**
     * ثبتِ یک نوبت روی روزِ داده‌شده و برگرداندنِ لحظهٔ دقیق.
     *
     * ساعت‌ها را عمداً پخش می‌کند: نوبتِ n اُمِ روز حولِ بازهٔ n اُم می‌افتد،
     * با چند دقیقه جابه‌جاییِ نامنظم. بدونِ این، دو مقالهٔ یک روز می‌توانستند
     * در یک دقیقه منتشر شوند و در فیدِ RSS پشتِ هم بچسبند.
     */
    private function reserve(Carbon $day): Carbon
    {
        $key = $day->toDateString();
        $index = $this->taken[$key] ?? 0;
        $quota = max(1, $this->quotaFor($day));

        $span = self::HOUR_MAX - self::HOUR_MIN;
        $hour = self::HOUR_MIN + (int) floor($span * $index / $quota);
        $minute = (crc32($key.'#'.$index) % 60);

        // اگر همان دقیقه قبلاً گرفته شده، جلو برو تا آزاد شود
        $stamp = $hour * 60 + $minute;
        while (in_array($stamp, $this->minutes[$key] ?? [], true)) {
            $stamp++;
        }

        $this->minutes[$key][] = $stamp;
        $this->taken[$key] = $index + 1;

        return $day->copy()->setTime(intdiv($stamp, 60), $stamp % 60);
    }

    /** شمارشِ آنچه از قبل روی تقویم نشسته — همهٔ نوع‌ها با هم */
    private function load(): void
    {
        try {
            $rows = Post::query()
                ->whereNotNull('published_at')
                ->where('published_at', '>=', now()->startOfDay())
                ->pluck('published_at');
        } catch (\Throwable $e) {
            return; // جدول هنوز مهاجرت نشده — تقویمِ خالی
        }

        foreach ($rows as $at) {
            $key = $at->toDateString();
            $this->taken[$key] = ($this->taken[$key] ?? 0) + 1;
            $this->minutes[$key][] = $at->hour * 60 + $at->minute;
        }
    }
}
