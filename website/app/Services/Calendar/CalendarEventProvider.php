<?php

namespace App\Services\Calendar;

use Illuminate\Support\Carbon;
use Illuminate\Support\Collection;

/**
 * یک «لایه» از تقویمِ کسب‌وکار.
 *
 * هر پیاده‌سازی یک منبعِ داده را به `CalendarItem` ترجمه می‌کند. قرارداد
 * عمداً یک متد دارد: هر چیزِ دیگری (برچسب، رنگ، آیکون) در
 * `config/calendar.php` است، پس افزودنِ لایه هیچ تغییری در این قرارداد
 * لازم ندارد.
 *
 * 🔴 **قاعدهٔ نشکستنی:** این متد نباید استثنا پرتاب کند.
 *
 * تقویم پنجِ منبع را کنار هم می‌گذارد و روی سروری اجرا می‌شود که ممکن است
 * هنوز همهٔ مهاجرت‌ها را نخورده باشد (مهاجرتِ پروداکشن در این پروژه با یک روتِ
 * مرورگری انجام می‌شود، نه SSH). اگر یک منبعِ نبود کلِ صفحه را ۵۰۰ کند، مدیر
 * تقویمی دارد که به‌خاطرِ جدولی که هرگز استفاده‌اش نمی‌کرد کار نمی‌کند.
 * پس هر پیاده‌سازی با `Schema::hasTable()` شروع می‌شود و در بدترین حالت
 * مجموعهٔ **خالی** برمی‌گرداند. `CalendarService` هم یک تورِ ایمنیِ دوم دارد.
 */
interface CalendarEventProvider
{
    /**
     * رویدادهای بازهٔ [from, to] — هر دو مرز **شامل**.
     *
     * @return Collection<int, CalendarItem>
     */
    public function getEvents(Carbon $from, Carbon $to): Collection;
}
