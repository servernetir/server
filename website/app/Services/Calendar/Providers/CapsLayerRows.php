<?php

namespace App\Services\Calendar\Providers;

/**
 * سقفِ ردیفِ یک لایه — **در خودِ پرس‌وجو**، نه بعد از خواندن.
 *
 * `CalendarService` هم سقف می‌گذارد، ولی آن‌جا دیر است: تا آن لحظه کلِ نتیجه
 * از دیتابیس خوانده و به شیء تبدیل شده. جدولِ `invoices` برای همیشه رشد
 * می‌کند و بازهٔ دوماهه روی حسابی با تاریخچهٔ چندساله می‌تواند ده‌ها هزار ردیف
 * باشد — روی همان دیتابیسی که نشست و کش هم رویش است.
 *
 * ⚠️ `+1` عمدی است و همان الگوی `DomainController::MAX_ROWS + 1` در این
 * پروژه: یک ردیفِ اضافه برداشته می‌شود تا `CalendarService` بفهمد **بریده
 * شده** و صریح گزارشش کند. بی‌آن، «دقیقاً ۳۰۰ ردیف» از «۳۰۰ تا از ۵۰۰۰» قابل
 * تشخیص نبود و صفحه بی‌صدا دروغ می‌گفت.
 */
trait CapsLayerRows
{
    protected function rowCap(): int
    {
        return max(1, (int) config('calendar.max_events_per_layer', 300)) + 1;
    }
}
