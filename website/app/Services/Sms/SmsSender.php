<?php

namespace App\Services\Sms;

/**
 * ارسال پیامک.
 *
 * دو متد و نه یکی، چون اپراتورهای ایرانی این دو را واقعاً متفاوت می‌فرستند:
 *
 *   send()     پیام آزاد — از خط خدماتی، ممکن است چند دقیقه تأخیر بخورد
 *   sendOtp()  کد یک‌بارمصرف — از مسیر «الگو/پترن» که اولویت تحویل دارد
 *
 * قبلاً یک متد بود و درایور از روی «آیا متن فقط رقم است؟» حدس می‌زد کدام
 * مسیر را برود. آن حدس روی پیام‌های عددی دیگر (مثلاً شمارهٔ فاکتور) اشتباه
 * می‌شد، پس صریح شد.
 */
interface SmsSender
{
    /** آیا واقعاً پیکربندی شده؟ اگر نه، فرستندهٔ لاگ جایش می‌نشیند. */
    public function enabled(): bool;

    /** نام ارائه‌دهنده — برای لاگ و گزارش */
    public function name(): string;

    /** true یعنی به ارائه‌دهنده تحویل شد؛ تحویل نهایی به گوشی تضمین نیست. */
    public function send(string $mobile, string $text): bool;

    /**
     * کد یک‌بارمصرف. درایورهایی که «الگو» دارند از آن استفاده می‌کنند،
     * بقیه به پیام معمولی برمی‌گردند.
     */
    public function sendOtp(string $mobile, string $code): bool;
}
