<?php

namespace App\Services\Provisioning;

use App\Models\Service;
use App\Services\ObjectStorage\HetznerObjectCosts;
use App\Support\ErrorTracker;

/** Creates one isolated VersityGW user and one owned bucket per paid service. */
class ObjectGatewayProvisioner implements Provisioner
{
    public function slug(): string
    {
        return 'hetzner_object_gateway';
    }

    public static function tenantId(Service $service): string
    {
        return 'sn-svc-'.$service->id;
    }

    public function create(Service $service): ProvisionResult
    {
        if (! $service->server) {
            return ProvisionResult::fail('Object Storage Gateway مشخص نیست.');
        }
        $spec = $this->spec($service);
        if ($spec === null) {
            ErrorTracker::noteOnce('provision', 'پلن Object Storage نامعتبر برای سرویس '.$service->id);

            return ProvisionResult::manual('پلن یا منطقهٔ Object Storage در Gateway تعریف نشده است.');
        }

        $gateway = app(ObjectGatewayBootstrapper::class)->ensureReady($service->server);
        if (! $gateway['ok']) {
            return $gateway['pending']
                ? ProvisionResult::manual($gateway['message'])
                : ProvisionResult::fail($gateway['message']);
        }

        $client = new ObjectGatewayClient($service->server);
        $tenantId = self::tenantId($service);
        $existing = $client->tenantState($tenantId);
        if ($existing === null) {
            return ProvisionResult::fail('وضعیت Gateway خوانده نشد؛ برای جلوگیری از تحویل دوگانه متوقف شد.');
        }
        if (is_array($existing)) {
            // A pre-provision password is generated by the generic pipeline and is
            // not an S3 secret. Rotate deterministically before adopting a tenant
            // left by an interrupted response, so a random local password is never delivered.
            $rotated = $client->rotateCredentials($tenantId);
            if (! $rotated['ok']) {
                return ProvisionResult::fail('باکت قبلی پیدا شد اما بازیابی دسترسی ناموفق بود: '.$rotated['reason']);
            }
            $secret = (string) ($rotated['data']['credentials']['secret_access_key'] ?? '');

            return $this->adopt($service, $existing, $secret, true);
        }

        $result = $client->createTenant($tenantId, $spec);
        if (! $result['ok']) {
            if ($result['transport']) {
                $after = $client->tenantState($tenantId);
                if (is_array($after)) {
                    $rotated = $client->rotateCredentials($tenantId);
                    $secret = (string) ($rotated['data']['credentials']['secret_access_key'] ?? '');
                    if ($rotated['ok'] && $secret !== '') {
                        return $this->adopt($service, $after, $secret, true);
                    }
                }
            }

            return ProvisionResult::fail('ساخت Object Storage ناموفق بود: '.$result['reason']);
        }

        $tenant = $result['data']['tenant'] ?? null;
        $secret = (string) ($result['data']['credentials']['secret_access_key'] ?? '');
        if (! is_array($tenant)) {
            return ProvisionResult::fail('Gateway پاسخ موفق داد اما اطلاعات باکت کامل نبود.');
        }

        return $this->adopt($service, $tenant, $secret, false);
    }

    public function suspend(Service $service): ProvisionResult
    {
        return $this->toggle($service, true);
    }

    public function unsuspend(Service $service): ProvisionResult
    {
        return $this->toggle($service, false);
    }

    public function terminate(Service $service): ProvisionResult
    {
        if (! $service->server) {
            return ProvisionResult::fail('Object Storage Gateway مشخص نیست.');
        }
        $days = max(1, (int) config('provisioning.object_gateway.termination_retention_days', 30));
        $result = (new ObjectGatewayClient($service->server))->retireTenant(self::tenantId($service), $days);

        return ($result['ok'] || $result['status'] === 404)
            ? ProvisionResult::success(null, null, null, ['retired' => true, 'retention_days' => $days])
            : ProvisionResult::fail('قرنطینه‌کردن باکت ناموفق بود: '.$result['reason']);
    }

    private function toggle(Service $service, bool $suspended): ProvisionResult
    {
        if (! $service->server) {
            return ProvisionResult::fail('Object Storage Gateway مشخص نیست.');
        }
        $result = (new ObjectGatewayClient($service->server))->setSuspended(self::tenantId($service), $suspended);

        return $result['ok']
            ? ProvisionResult::success((string) $service->username ?: null, null, null, ['suspended' => $suspended])
            : ProvisionResult::fail(($suspended ? 'تعلیق' : 'رفع تعلیق').' Object Storage ناموفق بود: '.$result['reason']);
    }

    private function spec(Service $service): ?array
    {
        $meta = app(HetznerObjectCosts::class)->metadataForPlan((string) $service->plan);
        $quota = config('provisioning.object_gateway.plans.'.(string) $service->plan);
        if (! is_array($meta) || ! is_numeric($quota) || (int) $quota <= 0) {
            return null;
        }

        return [
            'region' => (string) $meta['location'],
            'quota_bytes' => (int) $quota,
            'customer_ref' => (string) $service->customer_id,
        ];
    }

    private function adopt(Service $service, array $tenant, string $secret, bool $reused): ProvisionResult
    {
        $endpoint = (string) ($tenant['endpoint'] ?? '');
        $access = (string) ($tenant['access_key'] ?? '');
        $bucket = (string) ($tenant['bucket'] ?? '');
        if ($endpoint === '' || $access === '' || $bucket === '' || $secret === '') {
            return ProvisionResult::fail('اطلاعات اتصال Object Storage کامل نیست؛ سرویس تحویل‌شده اعلام نشد.');
        }

        return ProvisionResult::success($access, $secret, $endpoint, [
            'driver' => $this->slug(),
            'object_tenant_id' => (string) ($tenant['id'] ?? self::tenantId($service)),
            'endpoint' => $endpoint,
            'access_key' => $access,
            'bucket' => $bucket,
            'region' => (string) ($tenant['region'] ?? ''),
            'quota_bytes' => (int) ($tenant['quota_bytes'] ?? 0),
            'used_bytes' => (int) ($tenant['used_bytes'] ?? 0),
            'quota_enforcement' => 'metered-auto-suspend',
            'protocols' => ['s3-sigv4', 'multipart'],
            'reused' => $reused,
        ]);
    }
}
