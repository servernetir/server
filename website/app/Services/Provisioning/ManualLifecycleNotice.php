<?php

namespace App\Services\Provisioning;

use App\Models\ActivityLog;
use App\Models\Service;
use App\Services\Bale\Admin\AdminBaleRouter;
use App\Services\Notify\AdminNotifier;
use App\Support\ErrorTracker;

/**
 * 🔴 کارِ انسانیِ چرخهٔ عمر روی سرویسی که تحویلش دستی است.
 *
 * ═══ خرابی‌ای که این می‌بندد ═══
 *
 * لایسنس‌ها (و هر پکیجی که نه سرورِ ما را دارد نه ابری است) در **خریدِ اول**
 * درست مدیریت می‌شدند: `provision_status='manual'`، صفِ مدیر، و شمارش در
 * `SystemHealth`. ولی سه رخدادِ دیگر بی‌صدا رد می‌شدند، چون اتوماسیون فرض
 * می‌کرد محصولِ دستی فقط یک بار آدم لازم دارد:
 *
 *   · **تمدید** — `status` به `active` می‌رفت و سررسید جلو، و تنها ردش یک
 *     اعلانِ عمومیِ «پرداختِ موفق» بود که از تمدیدِ هاست فرقی نداشت. لایسنسِ
 *     بالادست تمدید نمی‌شد و پنلِ مشتریِ **پول‌داده** قفل می‌شد. و چون لایسنس
 *     ماهانه است، این پرتکرارترین حالت است — هر ماه، هر مشتری.
 *   · **تعلیق** — `ProvisioningService::suspend()` چون `server` نبود
 *     `ProvisionResult::success` می‌داد.
 *   · **خاتمه** — `releaseServer()` هم همین.
 *
 * 🔴 دو موردِ آخر پولِ در جریان‌اند و درست در جهتِ عکس: مشتری دیگر نمی‌پردازد
 * و ما همچنان به فروشندهٔ بالادست می‌پردازیم. خطِ قرمزِ «هرگز زیرِ بها» دقیقاً
 * همین است، و سکوتش یعنی ماه‌ها کسی نمی‌فهمد.
 *
 * ═══ چرا هم نشانه و هم اعلان ═══
 *
 * ⚠️ اعلان یک بار می‌آید؛ اگر مدیر آن ساعت نگاه نکند، رفته است. پس نشانه روی
 * **خودِ سرویس** می‌نشیند و `SystemHealth` تا پاک‌شدنش قرمز می‌مانَد. همان
 * قاعدهٔ ثبت‌شدهٔ پروژه: چیزی که قرار است از یک کارِ نکرده خبر دهد، نباید
 * تنها ردِ آن باشد.
 *
 * ⚠️ و ترتیب معنادار است: **اول نشانه، بعد اعلان**. اگر اعلان اول بود و
 * می‌ترکید، مدیر پیام می‌گرفت و صف خالی می‌مانْد — بدترین ترکیب، چون بعداً
 * هیچ‌چیز یادآوری نمی‌کرد.
 */
class ManualLifecycleNotice
{
    /** kind => [عنوانِ اعلان، متنِ کارِ لازم، اموجی] */
    private const KINDS = [
        'renew' => [
            'تمدیدِ سرویسِ دستی — کارِ شما لازم است',
            'مشتری تمدید را پرداخت کرده. لایسنس/سرویس را نزدِ تأمین‌کننده تمدید کنید، وگرنه در دورهٔ تازه قطع می‌شود.',
            '🔑',
        ],
        'suspend' => [
            'تعلیقِ سرویسِ دستی — کارِ شما لازم است',
            'سرویس در پنلِ ما معلق شد. لایسنس/سرویس را نزدِ تأمین‌کننده هم غیرفعال کنید، وگرنه هزینه‌اش پای ماست.',
            '⏸',
        ],
        'terminate' => [
            'خاتمهٔ سرویسِ دستی — کارِ شما لازم است',
            'سرویس بسته شد. لایسنس/سرویس را نزدِ تأمین‌کننده **ابطال** کنید، وگرنه ماهانه بابتش پول می‌دهیم.',
            '🛑',
        ],
    ];

    /**
     * اگر سرویس دستی است، نشانه بگذار و مدیر را خبر کن.
     *
     * ⚠️ برای سرویسِ خودکار (سرورِ ما یا ابری) هیچ کاری نمی‌کند — آن‌جا درایور
     * خودش کار را کرده و یک کارتِ اضافه فقط صف را شلوغ می‌کند. و صفِ شلوغ
     * دقیقاً همان چیزی است که ردیفِ واقعی را گم می‌کند.
     */
    public function flag(Service $service, string $kind): void
    {
        if (! isset(self::KINDS[$kind]) || ! $service->isManuallyDelivered()) {
            return;
        }

        [$title, $note, $emoji] = self::KINDS[$kind];

        // ── ۱) نشانهٔ ماندگار ──
        $service->flagManualAction($kind, $note);

        ActivityLog::forService($service, 'provision',
            'کارِ دستیِ «'.$kind.'» برای این سرویس ثبت شد: '.$note, 'system');

        // ── ۲) اعلان ──
        // 🔴 شکستش نباید خاتمه/تعلیق/تسویه را برگرداند، ولی بی‌رد هم نماند:
        //    این خروجی به **بیرون** می‌رود (بله/ایمیل)، پس دیتابیس سالم است و
        //    فقط مقصد نرسیده — همان مرزی که برای بقیهٔ آژیرها گذاشته شد.
        try {
            app(AdminNotifier::class)->event($title, [
                'مشتری'  => $service->customer
                    ? $service->customer->displayName().' ('.$service->customer->code.')'
                    : 'مشتری؟',
                'سرویس'  => (string) $service->name,
                'روی'    => (string) ($service->domain ?: '—'),
                'کارِ لازم' => $note,
            ], null, $emoji, [[
                ['text' => '👤 مشتری #'.$service->id,
                 'data' => AdminBaleRouter::CB_PREFIX.'c:'.$service->customer_id],
            ]]);
        } catch (\Throwable $e) {
            ErrorTracker::noteOnce('provision',
                'اعلانِ کارِ دستیِ «'.$kind.'» برای سرویسِ #'.$service->id.' نرفت: '.$e->getMessage(), 900);
        }
    }
}
