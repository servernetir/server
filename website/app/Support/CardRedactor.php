<?php

namespace App\Support;

/**
 * پوشاندنِ شمارهٔ کاملِ کارت در هر متنِ آزاد.
 *
 * ═══ رخداد (شهریور ۱۴۰۵) ═══
 * مشتری برای دریافتِ عودتِ وجه، شمارهٔ کاملِ ۱۶ رقمیِ کارتش را در متنِ تیکت
 * نوشت. تیکت بسته شد، پول برگشت، و آن شماره تا امروز **دست‌نخورده** در
 * `ticket_messages` ماند.
 *
 * 🔴 چرا محافظ‌های موجود نگرفتندش: قاعدهٔ «PAN کامل ذخیره نمی‌شود» در مسیرِ
 * احرازِ بانکی پیاده شده — آن‌جا کارت یک **فیلدِ فرم** است و کد رویش کنترل
 * دارد. ولی متنِ تیکت را خودِ مشتری می‌نویسد و هیچ فیلدی در کار نیست، پس آن
 * محافظ اصلاً سرِ راه نبود. **هر جا کاربر متنِ آزاد می‌نویسد، همان محافظ را
 * دوباره لازم داری.**
 *
 * بهایش هم واقعی است: نگهداریِ PAN کامل ما را مشمولِ الزاماتِ PCI می‌کند،
 * بی‌آنکه هیچ سودی داشته باشد — ما با آن شماره هیچ کاری نمی‌کنیم.
 */
final class CardRedactor
{
    /** ارقامِ لاتین + فارسی (U+06F0…) + عربی‌ـهندی (U+0660…) */
    private const D = '[0-9\x{06F0}-\x{06F9}\x{0660}-\x{0669}]';

    /** جداکننده‌های رایج بینِ گروه‌های چهارتایی — نیم‌فاصله هم هست */
    private const SEP = '[ \t\-\x{2010}-\x{2015}\x{200C}]';

    /**
     * ⚠️ فقط ۱۶ رقم، و **دقیقاً** ۱۶ رقم.
     *
     * دو تصمیمِ عمدی:
     *  · کارتِ بانکیِ ایران همیشه ۱۶ رقمی است. پذیرشِ بازهٔ ۱۳ تا ۱۹ (استانداردِ
     *    جهانیِ PAN) یعنی هر شمارهٔ پیگیری و شناسهٔ سفارشِ بلند هم نامزد شود.
     *  · «دقیقاً» یعنی رشتهٔ ۲۰ رقمی **اصلاً** بررسی نمی‌شود، نه اینکه پنجرهٔ
     *    ۱۶ رقمی‌اش را از تویش دربیاوریم. عددِ ۲۰ رقمی کارت نیست، و بریدنش
     *    فقط یک شناسهٔ سالم را خراب می‌کند.
     */
    private const LEN = 16;

    /**
     * متن با شمارهٔ کارتِ پوشانده — `621986******6137`.
     *
     * قالبِ خروجی عمداً همان ماسکی است که درگاهِ پرداخت برمی‌گرداند: شش رقمِ
     * اول (BIN، که بانک را می‌گوید) و چهار رقمِ آخر (که مشتری با آن کارتش را
     * می‌شناسد). همان دو چیزی که در `bank_accounts` هم مجاز است.
     */
    public static function mask(?string $text): ?string
    {
        if (blank($text)) {
            return $text;
        }

        // رشته‌های پیوستهٔ «رقم و جداکننده» را یکجا برمی‌داریم و بعد قضاوت
        // می‌کنیم. جایگزینِ ساده‌لوحانه — الگویی که مستقیم ۱۶ رقم می‌گیرد —
        // می‌توانست از وسطِ یک عددِ بلندتر شروع کند و آن را نصفه ماسک کند.
        $out = preg_replace_callback(
            '/'.self::D.'(?:'.self::SEP.'{0,2}'.self::D.')*/u',
            static function (array $m): string {
                $digits = self::ascii($m[0]);

                return self::isPan($digits)
                    ? substr($digits, 0, 6).'******'.substr($digits, -4)
                    : $m[0];
            },
            $text,
        );

        // preg_* روی متنِ نامعتبرِ UTF-8 مقدارِ null می‌دهد. متنِ اصلی بهتر از
        // متنِ نداشته است، ولی این یعنی ماسک نخورده — پس ساکت نمی‌مانیم.
        if ($out === null) {
            ErrorTracker::noteOnce('security',
                'CardRedactor نتوانست متن را پردازش کند (UTF-8 نامعتبر؟) — '
                .'شمارهٔ کارتِ احتمالی پوشانده نشد.', 3600);

            return $text;
        }

        return $out;
    }

    /** آیا این رشتهٔ رقمی، شمارهٔ کارت است؟ */
    public static function isPan(string $digits): bool
    {
        if (strlen($digits) !== self::LEN || ! ctype_digit($digits)) {
            return false;
        }

        // 🔴 دو نشانهٔ **مستقل**، با «یا» نه «و».
        //
        // فقط لومن: کارتی که مشتری یک رقمش را اشتباه تایپ کرده از تور رد
        // می‌شود — و آن شماره هنوز به اندازهٔ کافی افشاگر هست.
        // فقط BIN: جدولِ ما ۴۰ ردیف دارد و بانکِ نبود در جدول، کارتش ذخیره
        // می‌شود.
        //
        // هزینهٔ مثبتِ کاذب یک شناسهٔ ۱۶ رقمیِ ماسک‌شده است؛ هزینهٔ منفیِ کاذب
        // یک PAN که برای همیشه می‌مانَد. تقارن ندارند.
        return self::luhn($digits) || self::knownBin($digits);
    }

    /** ارقامِ فارسی/عربی → لاتین، و حذفِ هر چیزِ دیگر */
    private static function ascii(string $s): string
    {
        $s = strtr($s, [
            '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
            '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
            '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
            '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
        ]);

        return preg_replace('/\D/', '', $s) ?? '';
    }

    private static function knownBin(string $digits): bool
    {
        return config('banks.bins.'.substr($digits, 0, 6)) !== null;
    }

    private static function luhn(string $number): bool
    {
        $sum = 0;

        for ($i = 0; $i < 16; $i++) {
            $d = (int) $number[15 - $i];

            if ($i % 2 === 1) {
                $d *= 2;

                if ($d > 9) {
                    $d -= 9;
                }
            }

            $sum += $d;
        }

        return $sum % 10 === 0;
    }
}
