<?php

namespace App\Support;

/**
 * نرمال‌سازی شمارهٔ تلفن ایرانی — موبایل **و ثابت**.
 *
 * ═══ چرا کنارِ IranianMobile و نه داخلش ═══
 *
 * `IranianMobile` عمداً فقط موبایل را می‌شناسد و برای هر چیز دیگری `null`
 * می‌دهد — و درست هم هست، چون مصرف‌کننده‌اش پیامک است و پیامک به تلفن ثابت
 * نمی‌رود. ولی تلفن ابری **شمارهٔ ثابت** هم تحویل می‌دهد و آن‌جا `null` یعنی
 * «تماسِ این مشتری به هیچ پرونده‌ای نچسبید».
 *
 * پس این کلاس همان قواعدِ ارقامِ فارسی/عربی را دارد ولی دامنه‌اش بازتر است.
 * برای موبایل، خروجی‌اش **دقیقاً** با `IranianMobile::national()` یکی است —
 * تستی این را قفل می‌کند تا دو مسیرِ نرمال‌سازی هرگز واگرا نشوند.
 *
 * ═══ 🔴 مشکلِ پیش‌شمارهٔ گم‌شده ═══
 *
 * تلفن ابری «دفتر شما» شمارهٔ ثابت را **بدون پیش‌شمارهٔ شهر** می‌دهد. با داده
 * واقعی ثابت شد: شمارهٔ خودمان `02171057757` است و در فیلدِ `CalleeExtension`
 * به‌صورت `71057757` می‌آید.
 *
 * یعنی `34261000` می‌تواند در ارومیه، تهران یا اصفهان سه مشتریِ متفاوت باشد.
 * پس این کلاس چنین شماره‌ای را `KIND_LOCAL` علامت می‌زند و **قضاوت را به
 * فراخوان می‌سپارد** — تطبیقِ کورکورانه بدتر از نداشتنِ تطبیق است، چون
 * کارشناس به آن اعتماد می‌کند.
 */
final class IranianPhone
{
    /** موبایل: ده رقم، با ۹ شروع می‌شود — `9142223343` */
    public const KIND_MOBILE = 'mobile';

    /** ثابت با پیش‌شمارهٔ شهر: ده رقم — `2171057757` (۰۲۱ + ۷۱۰۵۷۷۵۷) */
    public const KIND_LANDLINE = 'landline';

    /** ثابت **بدون** پیش‌شماره: ۶ تا ۹ رقم — `34261000` ⚠️ مبهم */
    public const KIND_LOCAL = 'local';

    /** داخلیِ کوتاه: ۲ تا ۵ رقم — `201` */
    public const KIND_EXTENSION = 'extension';

    public const KIND_UNKNOWN = 'unknown';

    /**
     * فقط ارقامِ اسکی. ارقامِ فارسی و عربی **تبدیل** می‌شوند، نه حذف.
     *
     * 🔴 `preg_replace('/\D+/')` تنها، «۰۹۱۲…» را به رشتهٔ خالی می‌بَرد — یعنی
     * شمارهٔ کاملاً درستِ کاربری که با صفحه‌کلید فارسی تایپ کرده «نامعتبر»
     * می‌شود. همان درسی که در `IranianMobile` ثبت شده.
     */
    public static function digits(string $input): string
    {
        $fa = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
        $ar = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];

        $s = str_replace(
            array_merge($fa, $ar),
            array_merge(range(0, 9), range(0, 9)),
            $input,
        );

        return preg_replace('/\D+/', '', $s) ?? '';
    }

    /**
     * شکلِ متعارف برای **مقایسه** — بدون صفر و بدون کدِ کشور.
     *
     *   09142223343 · +989142223343 · 00989142223343 · 989142223343 → 9142223343
     *   02171057757 · +982171057757                                 → 2171057757
     *   71057757                                                    → 71057757
     *
     * `null` یعنی هیچ شکلِ قابلِ مقایسه‌ای در نیامد (رشتهٔ خالی، حروف، …).
     */
    public static function normalize(string $input): ?string
    {
        $d = self::digits($input);

        if ($d === '') {
            return null;
        }

        /*
        | ⚠️ ترتیب مهم است و شرطِ طول هم.
        |
        | «۹۸» را بی‌قید نمی‌بریم: `98123456` یک شمارهٔ محلیِ کاملاً معتبر است و
        | بریدنِ دو رقمِ اولش آن را به `123456` تبدیل می‌کند — یعنی تماسِ یک
        | مشتری روی پروندهٔ مشتریِ دیگری می‌نشیند. کدِ کشور فقط وقتی کدِ کشور
        | است که طولِ کل با آن بخواند.
        */
        // «۰۰۹۸» بی‌ابهام است: هیچ شمارهٔ داخلیِ ایران با ۰۰ شروع نمی‌شود
        if (str_starts_with($d, '0098')) {
            $d = substr($d, 4);
        } elseif (str_starts_with($d, '98') && strlen($d) === 12) {
            $d = substr($d, 2);
        }

        if (strlen($d) === 11 && $d[0] === '0') {
            $d = substr($d, 1);
        }

        return $d === '' ? null : $d;
    }

    /** نوعِ شماره، روی شکلِ نرمال‌شده. */
    public static function kind(string $input): string
    {
        $n = self::normalize($input);

        if ($n === null) {
            return self::KIND_UNKNOWN;
        }

        if (preg_match('/^9\d{9}$/', $n) === 1) {
            return self::KIND_MOBILE;
        }

        // ده رقم که با ۹ شروع نشود: پیش‌شمارهٔ شهر + شمارهٔ محلی
        if (preg_match('/^[1-8]\d{9}$/', $n) === 1) {
            return self::KIND_LANDLINE;
        }

        $len = strlen($n);

        if ($len >= 6 && $len <= 9) {
            return self::KIND_LOCAL;
        }

        if ($len >= 2 && $len <= 5) {
            return self::KIND_EXTENSION;
        }

        return self::KIND_UNKNOWN;
    }

    /**
     * آیا این دو شماره **می‌توانند** یکی باشند؟
     *
     * برای موبایل و ثابتِ کامل، برابریِ دقیق. برای شمارهٔ بی‌پیش‌شماره، تطبیقِ
     * پسوندی — چون `34261000` دنبالهٔ `4434261000` هست.
     *
     * ⚠️ «می‌توانند» عمدی است. این تابع **قطعیت نمی‌دهد**؛ تصمیمِ اینکه یک
     * تطبیقِ پسوندی به مشتری وصل شود یا نه، مالِ `CustomerMatcher` است که
     * می‌داند چند نفر خورده‌اند.
     */
    public static function couldMatch(string $a, string $b): bool
    {
        $na = self::normalize($a);
        $nb = self::normalize($b);

        if ($na === null || $nb === null) {
            return false;
        }

        if ($na === $nb) {
            return true;
        }

        // پسوند فقط وقتی معنا دارد که کوتاه‌تر واقعاً «محلیِ بی‌پیش‌شماره» باشد
        $short = strlen($na) <= strlen($nb) ? $na : $nb;
        $long = $short === $na ? $nb : $na;

        if (self::kind($short) !== self::KIND_LOCAL) {
            return false;
        }

        /*
        | 🔴 سقفِ «کوتاه‌تر دستِ‌کم ۶ رقم» در `KIND_LOCAL` تضمین شده. بدونِ آن،
        | یک داخلیِ سه‌رقمیِ `343` با هر شماره‌ای که به ۳۴۳ ختم شود جفت می‌شد.
        */
        return str_ends_with($long, $short);
    }
}
