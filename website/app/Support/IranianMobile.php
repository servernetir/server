<?php

namespace App\Support;

/**
 * نرمال‌سازی شمارهٔ موبایل ایرانی — **یک جا**، برای همهٔ کانال‌ها.
 *
 * ⚠️ چرا مشترک: هر کانالی (آی‌پی‌پنل، بله، سفیر) قالبِ خودش را می‌خواهد، ولی
 * همه از **همان ورودیِ کاربر** شروع می‌کنند. نگه‌داشتنِ منطقِ تبدیل در چند
 * کلاس یعنی دیر یا زود یکی از آن‌ها ارقامِ فارسی را جا می‌اندازد و همان کانال
 * بی‌صدا خاموش می‌شود — دقیقاً همان الگویی که در فهرستِ الگوها و در اسکریپتِ
 * کدِ ورود تکرار شد.
 *
 * 🔴 ارقامِ فارسی و عربی **تبدیل** می‌شوند، نه حذف. `preg_replace('/\D+/')`
 * تنها، «۰۹۱۲…» را به رشتهٔ خالی تبدیل می‌کند — یعنی شمارهٔ کاملاً درستِ
 * کاربری که با صفحه‌کلیدِ فارسی تایپ کرده، به «نامعتبر» می‌رسد.
 */
final class IranianMobile
{
    /**
     * بخشِ ملیِ ده‌رقمی (`9142223343`)، یا `null` اگر شمارهٔ ایرانیِ معتبر نباشد.
     *
     * همهٔ قالب‌های رایج پذیرفته می‌شوند: `09…` · `+989…` · `00989…` · `989…` ·
     * `9…` و هر کدام با ارقامِ فارسی/عربی.
     */
    public static function national(string $input): ?string
    {
        $fa = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
        $ar = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];

        $s = str_replace(
            array_merge($fa, $ar),
            array_merge(range(0, 9), range(0, 9)),
            $input,
        );

        $d = preg_replace('/\D+/', '', $s) ?? '';

        foreach (['0098' => 4, '98' => 2, '0' => 1] as $prefix => $len) {
            if (str_starts_with($d, (string) $prefix)) {
                $d = substr($d, $len);
                break;
            }
        }

        return preg_match('/^9\d{9}$/', $d) === 1 ? $d : null;
    }

    /** `+989142223343` — قالبِ E.164، همان چیزی که آی‌پی‌پنل می‌خواهد */
    public static function e164(string $input): ?string
    {
        $n = self::national($input);

        return $n === null ? null : '+98'.$n;
    }

    /**
     * `989142223343` — بدونِ `+` و بدونِ صفر.
     *
     * ⚠️ سفیرِ بله دقیقاً همین را می‌خواهد و `09…` را با کدِ خطای ۸
     * (InvalidPhone) رد می‌کند.
     */
    public static function bare(string $input): ?string
    {
        $n = self::national($input);

        return $n === null ? null : '98'.$n;
    }
}
