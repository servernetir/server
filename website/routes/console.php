/*
| ضربانِ کرون — هر دقیقه یک مهرِ زمانی می‌نویسد. بدونِ این، وقتی سفارشی تحویل
| نمی‌شود هیچ راهی نبود بفهمیم «کرونِ سرور اصلاً اجرا می‌شود یا نه» و ساعت‌ها
| دنبالِ باگِ کد می‌گشتیم در حالی که مشکل نبودنِ کرون بود.
|
| 🔴 در **فایل** می‌نویسد، نه در کش. قبلاً `cache()->put(...)` بود و کش روی
| دیتابیس است — یعنی همان دیتابیسی که وقتی می‌مُرد، کرون هم می‌مُرد. ضربانی که
| با بیمار می‌میرد، به هیچ دردی نمی‌خورد: دقیقاً در لحظه‌ای که باید فریاد بزند
