// قبلی یک ستونِ `last_error` بود که کسی نمی‌خوانَد. حالا ردیف در
// `provision_status='releasing'` می‌مانَد، این کرون هر ساعت دوباره تلاش می‌کند، و
// `SystemHealth::cloudRelease()` تا بسته‌شدنش قرمز است.
//
// ⚠️ هرگز چیزی نمی‌خرد: پرس‌وجویش روی `Service::DEAD_STATUSES` قفل است.
Schedule::command('cloud:release-retry')
    ->hourly()
    ->withoutOverlapping(30);

// کاتالوگ و قیمتِ سرورِ ابری — کارفرما: «هر دو روز یک‌بار، ۲ شب، هم قیمت هم
// پکیج‌ها».
//
// ⚠️ ساعت به وقتِ **UTC** است (config/app.php ثابت روی UTC). تهران +۳:۳۰، پس
// «۲ بامدادِ تهران» = ۲۲:۳۰ UTC روزِ قبل. اگر ۰۲:۰۰ UTC می‌گذاشتیم، در تهران
// ۵:۳۰ صبح می‌شد — نه آن چیزی که خواسته شده.
//
// این یک اجرا **هم پکیج‌ها را می‌آورد هم قیمت‌ها را بازمحاسبه می‌کند**:
// `cloud:sync` مشخصات و بهایِ تمام‌شده را تازه می‌کند و در همان گذر قیمتِ فروش
// را با نرخِ روزِ یورو می‌سازد. پس یک کرون کافی است، نه دو.
Schedule::command('cloud:sync')
    ->cron('30 22 */2 * *')
    ->withoutOverlapping(60);

// بازمحاسبهٔ قیمتِ تومانی با نرخِ روزِ یورو — روزانه و بی‌تماسِ API.
// جدا از سینکِ کامل است چون نرخِ ارز روزانه می‌جنبد ولی مشخصاتِ پلن‌ها ماه‌ها
// ثابت می‌مانند؛ بی‌این، قیمتِ تومانی تا سینکِ بعدی کهنه می‌ماند.
// fx:dollar ساعتی می‌دود، پس نرخ همیشه تازه است.
Schedule::command('cloud:sync --prices')
    ->dailyAt('05:40')
    ->withoutOverlapping(45);

// یادآوریِ روزانهٔ تقویم به مدیر (بله + ایمیل).
//
// ساعت به وقتِ **UTC** است — قاعدهٔ ثابتِ این پروژه. ۰۴:۳۰ UTC یعنی حدودِ
// ۰۸:۰۰ صبحِ تهران: اولِ روزِ کاری، نه نیمه‌شب.
//
// ⚠️ فرمان خودش وقتی چیزی نباشد **ساکت** می‌ماند و گلوگاهِ روزانه دارد، پس
// اجرای روزانه پیامِ تکراری نمی‌سازد. کلِ منطقِ «آیا ارزشِ گفتن دارد» داخلِ
// خودِ فرمان است، نه در این زمان‌بندی.
Schedule::command('calendar:remind')
    ->dailyAt('04:30')
    ->withoutOverlapping(30);
/*
|--------------------------------------------------------------------------
| موتورِ جذبِ مشتریِ خارجی
|--------------------------------------------------------------------------
| زنجیره عمداً چهار تکه است و هر تکه جدا اجرا می‌شود:
|
|   discover → enrich → queue → send        و به‌موازاتش: inbox
|
| چرا جدا: هر تکه سرعت و ریسکِ متفاوتی دارد. `enrich` چند تماسِ HTTP و یک
| تماسِ مدل به ازای هر سرنخ می‌زند (کُند و گران)، `send` باید آهسته و پراکنده
| باشد، و `inbox` باید **سریع** باشد چون تنها چیزی است که فالوآپِ اشتباه را
| متوقف می‌کند. اگر همه در یک فرمان بودند، کندیِ یکی، فوریتِ دیگری را می‌خورد.
|
| 🔴 هیچ‌کدام بدونِ `CRM_AUTOPILOT=true` ایمیلی بیرون نمی‌فرستند. سه‌تای اول
| فقط می‌نویسند و در پنل می‌گذارند؛ `crm:send` با خلبانِ خاموش بی‌صدا برمی‌گردد.
*/

// کشفِ سرنخِ تازه — روزی یک‌بار کافی است، بیشترش فقط سهمیهٔ Places را می‌سوزاند.
Schedule::command('crm:discover')
    ->dailyAt('04:20')
    ->when(fn () => filled(config('crm.discovery.places_key')))
    ->withoutOverlapping(60);

// ممیزیِ سایت + یافتنِ نشانی + مشاهده. سنگین‌ترین تکه، پس دسته‌های کوچک و مکرر.
Schedule::command('crm:enrich --limit=5')
    ->hourly()
    ->withoutOverlapping(45);

// نوشتنِ پیامِ سرنخ‌های سررسیده. پیش از پنجرهٔ ارسال اجرا می‌شود تا صف پر باشد.
Schedule::command('crm:queue --limit=10')
    ->dailyAt('04:50')
    ->withoutOverlapping(45);

/*
| تخلیهٔ صف — ساعتی، و خودِ فرمان پنجرهٔ زمانی و سقفِ روزانه را چک می‌کند.
|
| ⚠️ `withoutOverlapping(20)` و نه بیشتر: این فرمان بینِ ارسال‌ها عمداً
| ۲۵ تا ۹۵ ثانیه می‌خوابد (الگویِ انسانی)، پس یک اجرا می‌تواند چند دقیقه طول
| بکشد. قفلِ کوتاه یعنی اگر اجرایی بد بمیرد، ساعتِ بعد دوباره راه می‌افتد.
*/
Schedule::command('crm:send')
    ->hourly()
    ->when(fn () => (bool) config('crm.autopilot'))
    ->withoutOverlapping(20);

/*
| خواندنِ جواب‌ها — هر ۱۵ دقیقه.
|
| 🔴 چرا این‌قدر مکرر: بدترین اتفاقِ ممکن این است که کسی جواب بدهد «قیمت چند؟»
| و فالوآپِ خودکارِ «یادآوری» برایش برود. این فرمان تنها چیزی است که جلویش را
| می‌گیرد — و همین‌جا هم هست که «no» به فهرستِ سیاه تبدیل می‌شود.
*/
Schedule::command('crm:inbox --days=5')
    ->everyFifteenMinutes()
    ->when(fn () => filled(config('crm.inbox.host')) && filled(config('crm.inbox.pass')))
    ->withoutOverlapping(20);

/*
|--------------------------------------------------------------------------
| صندوق‌های ایمیلِ مدیریتی — ceo@ · support@ · info@
|--------------------------------------------------------------------------
| دو کارِ جدا، عمداً:
|
|   mailbox:sync   ساعتی — فقط می‌خواند. ارزان است، پس پنل همیشه تازه است.
|   mailbox:digest روزی یک‌بار، اولِ صبح — دسته‌بندی + یک پیام در بله.
|
| اگر یکی بودند، پنل به دورهٔ گزارش گره می‌خورد: یعنی نامه‌ای که ساعت ۹ صبح
| آمده تا فردا صبح در پنل دیده نمی‌شد.
|
| 🔴 نامهٔ سیستمیِ خودمان (موضوع با پیشوندِ `[سرورنت]`) در گزارش نمی‌آید.
| `AdminNotifier` هر رویداد را همان لحظه هم به بله می‌فرستد هم به ایمیلِ مدیر؛
| بدونِ این فیلتر، گزارشِ روزانه فقط تکرارِ چیزهایی می‌شد که قبلاً خوانده شده‌اند
| و ظرفِ یک هفته کسی بازش نمی‌کرد.
*/

/*
| 🔴 `when()` روی هر دو: تا وقتی رمزی در .env نگذاشته‌ای، این کرون‌ها اصلاً
| بیدار نمی‌شوند.
|
| بدونِ این، روی پروداکشن هر ۱۵ دقیقه یک هشدارِ «پیکربندی نشده» در لاگ می‌نشست
| — روزی ۹۶ خط. لاگی که پر از هشدارِ بی‌معنی است، همان لاگی است که روزِ خرابیِ
| واقعی کسی نمی‌خواندش.
*/
Schedule::command('mailbox:sync')
    ->hourly()
    ->when(fn () => filled(config('mailboxes.accounts')))
    ->withoutOverlapping(45);

/*
| ⚠️ ساعت‌ها UTC اند (config/app.php ثابت روی UTC). تهران +۳:۳۰ →
| ۰۴:۳۰ UTC = ۸:۰۰ صبحِ تهران — و همین یک‌بار در روز، بس.
|
| 🔴 قبلاً `30 4,14` بود (صبح و عصر). کاربر صریحاً یک گزارش در روز خواست:
| گزارشی که روزی دو بار بیاید، دومی‌اش خوانده نمی‌شود و اولی را هم بی‌ارزش
| می‌کند. اگر روزی خواستی برش گردانی، بدان که این یک تصمیم بود نه فراموشی.
*/
Schedule::command('mailbox:digest --skip-sync')
    ->cron('30 4 * * *')
    ->when(fn () => filled(config('mailboxes.accounts')))
    ->withoutOverlapping(45);
