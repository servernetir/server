<?php

namespace Database\Seeders;

use App\Models\NotificationTemplate;
use App\Support\AdminAlerts;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Schema;

/**
 * اعلان‌هایی که به **خودِ مدیر** می‌روند — تا بشود خاموششان کرد و متنشان را نوشت.
 *
 * ═══ خرابی‌ای که این می‌بندد ═══
 *
 * ۲۵ فراخوانِ `AdminNotifier::event()` عنوان و متنِ سخت‌کد داشتند و هیچ کلیدِ
 * خاموشی. مدیر نمی‌توانست بگوید «این یکی را دیگر نفرست» — و اعلانِ پرتکرارِ
 * کم‌ارزش دقیقاً همان چیزی است که باعث می‌شود اعلانِ **مهم** هم دیده نشود.
 * همان «آژیرِ همیشه‌روشن» که در این پروژه بارها گاز گرفته.
 *
 * ═══ تگ‌ها از کجا می‌آیند ═══
 *
 * ⚠️ فهرستِ `variables` هر ردیف **از خودِ فراخوانی استخراج شده**، نه از حدس:
 * برچسبِ هر ردیفِ `$rows` مستقیماً یک تگ است. پس `{مشتری}` و `{مبلغ}` بدونِ
 * هیچ تغییری در آن ۲۵ فراخوان کار می‌کنند.
 *
 * ⚠️ چیپِ اضافه در این فهرست بی‌خطر نیست: صفحهٔ ویرایش آن را به مدیر پیشنهاد
 * می‌دهد، مدیر در متن می‌گذاردش، و چون هیچ‌وقت پر نمی‌شود
 * `NotificationTemplate::body()` کلِ متن را کنار می‌گذارد و به پیش‌فرض
 * برمی‌گردد — یعنی ویرایشِ مدیر بی‌صدا بی‌اثر می‌شود.
 *
 * ═══ 🔴 چه چیزی عمداً این‌جا نیست ═══
 *
 * `AdminBaleGate` (کدِ تأییدِ اتصالِ کنسولِ مدیر) و کدهای تأییدِ نوشتنِ
 * دیده‌شدنی توسطِ مشتری **کلید نمی‌گیرند**. خاموش‌کردنشان یعنی مدیر خودش را
 * از کنسول بیرون بیندازد و راهی برای برگشت نداشته باشد. اعلانی که تنها راهِ
 * دسترسی است، نباید قابلِ خاموش‌شدن باشد.
 */
class AdminNotificationTemplateSeeder extends Seeder
{
    public function run(): void
    {
        if (! Schema::hasTable('notification_templates')
            || ! Schema::hasColumn('notification_templates', 'audience')) {
            return;
        }

        foreach (AdminAlerts::EVENTS as $key => [$title, $group, $vars]) {
            /*
            | ⚠️ `firstOrCreate` — ردیفِ موجود دست نمی‌خورد.
            |
            | این seeder روی هر `/system/migrate` می‌دود. اگر مقدارها را
            | بازنویسی می‌کرد، متنی که مدیر نوشته با دیپلویِ بعدی برمی‌گشت به
            | پیش‌فرض — و او فکر می‌کرد ویرایشش ذخیره نشده.
            */
            $tpl = NotificationTemplate::firstOrCreate(['key' => $key], [
                'title'     => $title,
                'group'     => $group,
                'audience'  => 'admin',
                // 🔴 `bale_body` عمداً خالی: خالی یعنی «متنِ پیش‌فرضِ کد».
                //    پرکردنش با یک کپیِ متنِ کد یعنی از فردا دو منبعِ حقیقت،
                //    و تغییرِ کد دیگر در اعلان دیده نمی‌شود.
                'bale_body' => null,
                'variables' => $vars,
                'is_active' => true,
            ]);

            /*
            | فهرستِ تگ‌ها **به‌روز** می‌شود حتی روی ردیفِ موجود — برخلافِ متن.
            |
            | تگ‌ها از کد می‌آیند نه از سلیقهٔ مدیر: اگر فراخوانی ردیفِ تازه‌ای
            | اضافه کند، صفحهٔ ویرایش باید بشناسدش. و اگر ردیفی حذف شود،
            | ماندنش در فهرست یعنی مدیر تگی را پیشنهاد می‌گیرد که هیچ‌وقت پر
            | نمی‌شود — و آن‌وقت کلِ متنش بی‌صدا کنار گذاشته می‌شود.
            */
            if (! $tpl->wasRecentlyCreated
                && ($tpl->variables !== $vars || $tpl->audience !== 'admin')) {
                $tpl->forceFill(['variables' => $vars, 'audience' => 'admin'])->save();
            }
        }
    }
}
