// Build only from the already vendored noVNC sources. No network or credentials.
import {build} from 'esbuild';
import {createHash} from 'node:crypto';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const dir=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(dir,'../..');
const vendor=path.join(root,'website/public/assets/js/novnc');
const license=(await readFile(path.join(vendor,'LICENSE.txt'),'utf8'))+'\n\nPako:\n'+(await readFile(path.join(vendor,'vendor/pako/LICENSE'),'utf8'));
const notice='/*\n'+license+'\nSource: https://github.com/servernetir/server/tree/8b819322170187cd195ce8c821313975ac7aadff/website/public/assets/js/novnc\nMPL-2.0: https://mozilla.org/MPL/2.0/\n*/\n';
const result=await build({absWorkingDir:root,entryPoints:['website/public/assets/js/novnc/core/rfb.js'],
  bundle:true,format:'esm',platform:'browser',target:'es2022',minify:true,legalComments:'inline',write:false,metafile:true});
if(Object.values(result.metafile.outputs).some(o=>o.imports.length))throw Error('Browser bundle has unresolved imports');
const source=notice+result.outputFiles[0].text;
const hash=createHash('sha256').update(source).digest('hex');
await writeFile(path.join(dir,'novnc-source.mjs'),'// Generated by build.mjs from vendored sources; do not edit.\nexport const NOVNC_PATH='+JSON.stringify('/novnc-'+hash.slice(0,16)+'.js')+';\nexport const NOVNC_SOURCE='+JSON.stringify(source)+';\n');
await mkdir(path.join(dir,'dist'),{recursive:true});
await build({absWorkingDir:dir,entryPoints:['worker.mjs'],outfile:'dist/worker.mjs',bundle:true,
  format:'esm',platform:'neutral',target:'es2022',minify:false,legalComments:'inline'});
console.log(JSON.stringify({browserBundleBytes:Buffer.byteLength(source),sha256:hash,unresolvedImports:0,worker:'dist/worker.mjs'}));
